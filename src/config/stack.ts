/** Canonical slug: synonyms are merged, parent/child relationships are NOT. */
export const canonicalTech = (slug: string): string => STACK_SYNONYMS[slug] ?? slug;
export const parentTech = (slug: string): string | undefined => STACK_PARENTS[canonicalTech(slug)];
/** Minimum references (own tags only) for a technology to get its own /stack page. */
export const STACK_PAGE_MIN = 3;

export const techLabel = (slug: string): string =>
  STACK[slug]?.label ?? slug.split('-').map((w) => w.charAt(0).toUpperCase() + w.slice(1)).join(' ');
