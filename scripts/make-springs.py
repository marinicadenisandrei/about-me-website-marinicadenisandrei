#!/usr/bin/env python3
"""Emits src/styles/motion.css: spring easings as CSS linear() (sampled damped-spring solutions)
with cubic-bezier fallbacks for browsers without linear(). Run: python3 scripts/make-springs.py"""
import math, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
def spring(mass, stiffness, damping, n=40, dur=1.0):
    w0 = math.sqrt(stiffness / mass); zeta = damping / (2 * math.sqrt(stiffness * mass))
    pts = []
    for i in range(n + 1):
        t = dur * i / n
        if zeta < 1:
            wd = w0 * math.sqrt(1 - zeta * zeta)
            x = 1 - math.exp(-zeta * w0 * t) * (math.cos(wd * t) + (zeta * w0 / wd) * math.sin(wd * t))
        else:
            x = 1 - math.exp(-w0 * t) * (1 + w0 * t)
        pts.append(round(x, 4))
    pts[-1] = 1.0
    return ', '.join(f'{p}' if i % 4 else f'{p} {round(100*i/n)}%' for i, p in enumerate(pts))
springs = {
  # name: (mass, stiffness, damping, duration-s, fallback)
  'snappy': (1, 400, 30, 0.45, 'cubic-bezier(0.2, 0.9, 0.3, 1.05)'),
  'smooth': (1, 170, 26, 0.8,  'cubic-bezier(0.16, 1, 0.3, 1)'),
  'bouncy': (1, 300, 16, 0.9,  'cubic-bezier(0.34, 1.56, 0.64, 1)'),
}
out = ['/* Generated by scripts/make-springs.py — iOS-style springs as linear() easings with fallbacks. */', ':root {']
for k, (m, s, d, dur, fb) in springs.items():
    out.append(f'  --spring-{k}: {fb};'); out.append(f'  --dur-{k}: {dur}s;')
out.append('}'); out.append('@supports (animation-timing-function: linear(0, 1)) {'); out.append('  :root {')
for k, (m, s, d, dur, fb) in springs.items():
    out.append(f'    --spring-{k}: linear({spring(m, s, d, dur=dur)});')
out.append('  }'); out.append('}')
open(os.path.join(ROOT, 'src/styles/springs.css'), 'w').write('\n'.join(out) + '\n')
print('✔ src/styles/springs.css')
